# Round 33: writes tools/v12/survey.md from survey.json and fieldmap.json (run survey.py, then fieldmap.py, then this).
#     python -I tools/v12/survey_md.py
import json, os
from collections import Counter, defaultdict
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
d = json.load(open('tools/v12/survey.json'))
rows = d['rows']
fm = json.load(open('tools/v12/fieldmap.json'))
areas = ['AI', 'weapons', 'damage', 'input', 'HUD', 'sound', 'network', 'mission', 'render', 'platform',
         'C runtime', 'not converted', 'other']
cnt = defaultdict(Counter)
for r in rows:
    cnt[r['area']][(r['kind'], r['ported'])] += 1
m4 = [int(p['off10'], 16) for p in fm['pairs'] if p['delta'] == -4]
v4 = fm['deltas'].get('-4', 0)
L = []
L.append('# 1.2 sim changes still to port (survey, round 33)\n')
L.append('Generated by `tools/v12/survey.py` (pairs, ported status, areas; `survey.json`), `tools/v12/fieldmap.py` '
         '(record-field offsets; `fieldmap.json`) and `tools/v12/survey_md.py` (this file). Read-only analysis of '
         'GameRip/HGSIM.DLL (1.0) and GameRip_12/hgsim.dll (1.2); nothing here is ported. Ports need Diego\'s go.\n')
L.append('## Method and limits\n')
L.append('- Functions: `push ebp / mov ebp, esp` starts after a ret / int3 / nop, and the target of every `call` in '
         '.text (jmp thunks followed): %d in 1.0, %d in 1.2 (a function needs 4 instructions to count).'
         % (d['n10'], d['n12']))
L.append('- Pairs: exact listings first (funcmap.json, addresses and stack offsets normalised), then equal listings, '
         'then the most similar unpaired listing (difflib ratio >= 0.6). %d identical apart from addresses; %d '
         'functions of 1.0 without a 1.2 partner.' % (d['same'], len(d['gone10'])))
L.append('- "layout": differs only in displacements (the record shift below); our sim keeps 1.0\'s layout, so these '
         'need no port, only the offset map when 1.2 code is carried over. "logic": real change. "new": 1.2 function '
         'with no 1.0 partner.')
L.append('- Ported: our C body of the 1.0 twin mentions 1.2, or the 1.2 address is cited in src. Partial ports count '
         'as ported; a "logic" row marked ported may still have unported parts.')
L.append('- Area: keywords in our C text of the 1.0 twin (for a new function, of its nearest paired 1.2 neighbour). '
         'Approximate: "other" is what the keywords could not place.\n')
L.append('## Counts (not yet ported)\n')
L.append('| area | logic | new | layout only | already ported (logic / new) |')
L.append('|---|---|---|---|---|')
tot = Counter()
for a in areas:
    c = cnt[a]
    lg, nw, ly = c[('logic', False)], c[('new', False)], c[('layout', False)]
    pl, pn = c[('logic', True)], c[('new', True)]
    tot.update(dict(lg=lg, nw=nw, ly=ly, pl=pl, pn=pn))
    L.append('| %s | %d | %d | %d | %d / %d |' % (a, lg, nw, ly, pl, pn))
L.append('| **total** | **%d** | **%d** | **%d** | **%d / %d** |\n' % (tot['lg'], tot['nw'], tot['ly'], tot['pl'], tot['pn']))
L.append('## Unported logic changes by area (largest first; d = instructions added + removed)\n')
for a in areas:
    rs = sorted([r for r in rows if r['area'] == a and r['kind'] == 'logic' and not r['ported']], key=lambda r: -r['d'])
    if not rs:
        continue
    L.append('### %s (%d)\n' % (a, len(rs)))
    for r in rs:
        L.append('- 1.2 %s = 1.0 %s, d=%d of %d, `%s`' % (r['a12'], r['a10'], r['d'], r['n'], r['c']))
    L.append('')
L.append('## New 1.2 functions not ported, by area (nearest paired neighbour\'s file)\n')
for a in areas:
    rs = sorted([r for r in rows if r['area'] == a and r['kind'] == 'new' and not r['ported']], key=lambda r: r['a12'])
    if not rs:
        continue
    L.append('### %s (%d)\n' % (a, len(rs)))
    L.append(', '.join('%s (%d, near `%s`)' % (r['a12'], r['n'], r['c']) for r in rs))
    L.append('')
L.append('## Record layout map (1.0 -> 1.2)\n')
L.append('- **Object / unit record** (the 0x109e8b40 table\'s records and the unit records they point at): 1.2 removed '
         'one dword; every field from +%s up to +%s sits 4 bytes lower in 1.2 (+0x1c -> +0x18, +0x28 -> +0x24, '
         '+0x54 -> +0x50, ...), %d votes. Seen in round 33: player record unit +0x28 -> +0x24, flags +0x1c -> +0x18; '
         'unit control block +0x54 -> +0x50. Fields below +0x18 unchanged.' % (hex(min(m4)), hex(max(m4)), v4))
L.append('- **The effect pool record** (pool 1.0 0x10217c20, 1000 records): 1.0 records of 0x57e bytes, 1.2 particle '
         'systems of 0x406 bytes in the same pool; object / update / draw / argument +0x552 / +0x556 / +0x55a / +0x57a '
         'in 1.0 = +0x332 / +0x336 / +0x33a / +0x366 in 1.2. Already mapped in `src/sim/fx/w32.h` (W32_REC_*, round '
         '32); the 1.2 functions 0x10079c54 (= 1.0 Sim_10090c7d) and 0x100be1aa / 0x100be7a6 (= Sim_100d8d0a / '
         'Sim_100d9306) read them.')
L.append('- The other displacement votes are global-array bases (1.0 and 1.2 addresses of the same table), not fields.')
L.append('- Full list: `tools/v12/fieldmap.json`.\n')
L.append('## Recommended round order\n')
L.append('By what a player notices first, and by size; every round with its own checker specs against 1.2\'s code.\n')
big = sorted([r for r in rows if r['kind'] == 'logic' and not r['ported']], key=lambda r: -r['d'])[:12]
L.append('Largest unported logic changes: ' + ', '.join('1.2 %s = 1.0 %s (d=%d, `%s`)' % (r['a12'], r['a10'], r['d'],
         r['c']) for r in big) + '.\n')
L.append('1. **Footsteps and the gun** (okayed by Diego earlier).')
L.append('2. **Gear movement and world AI**: the largest logic changes (`w16_move.c`, `w15_world.c`), target '
         'selection (`w9d_select.c`), groups and ranges.')
L.append('3. **Mission flow**: the in-mission / mission-end menu (1.0 0x10048f02), 0x1003f3f8, gear and state.')
L.append('4. **Input**: the changed and new functions near the key / command code (new 1.2 commands; the force-'
         'feedback DLL use).')
L.append('5. **Animation, weapons, damage, HUD, sound**.')
L.append('6. **The small ones** (d <= 10): mostly constants and short branches; a sweep round with one spec each.')
L.append('7. **Network**: last (Diego: network reworked later).')
L.append('8. **C runtime copies**: only where behaviour shows (string / locale changes); otherwise not needed.')
open('tools/v12/survey.md', 'w').write('\n'.join(L) + '\n')
print('survey.md: %d lines; not ported: logic %d, new %d, layout %d' % (len(L), tot['lg'], tot['nw'], tot['ly']))
