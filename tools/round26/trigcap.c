/*
 * Round 26: captures the original sine / arctangent tables (DECISIONS.md, round 26). Maps HGSIM.DLL without running
 * its start-up code or resolving its imports (the table builder 0x100846e0 needs neither: it calls the DLL's own
 * sin 0x100ff644 / atan 0x10100044, the C runtime's x87 fsin / fpatan wrappers), sets the game's x87 control word
 * 0x27f, runs the builder on this CPU and writes the 1024 floats and the two words after them as a C table.
 *   i686-w64-mingw32-gcc -O1 -o trigcap.exe trigcap.c
 *   trigcap.exe <HGSIM.DLL> <output .inc>
 */
#include <stdio.h>
#include <stdint.h>
#include <windows.h>

int main(int argc, char **argv)
{
    HMODULE dll;
    uintptr_t base;
    const uint32_t *sine, *atan;
    unsigned short cw = 0x27f;
    FILE *out;
    int i;

    if (argc != 3)
        return 2;
    dll = LoadLibraryExA(argv[1], NULL, DONT_RESOLVE_DLL_REFERENCES);
    if (dll == NULL) {
        fprintf(stderr, "cannot map %s (%lu)\n", argv[1], GetLastError());
        return 1;
    }
    base = (uintptr_t)dll;
    if (base != 0x10000000u) {
        fprintf(stderr, "mapped at %08lx, not at its base 0x10000000\n", (unsigned long)base);
        return 1;
    }
    __asm__ volatile("fninit; fldcw %0" : : "m"(cw));
    ((int(__cdecl *)(void))(base + 0x846e0))();
    sine = (const uint32_t *)(base + 0x3719a0);
    atan = (const uint32_t *)(base + 0x3721c0);
    out = fopen(argv[2], "w");
    if (out == NULL)
        return 1;
    fprintf(out, "/* Generated by tools/round26/trigcap.c: the original 0x100846e0's tables, run on the game machine's\n"
                 "   CPU (DECISIONS.md, round 26). 0x103719a0: sin(i * pi / 1024) for i < 512, then the word 0x103721a0;\n"
                 "   0x103721c0: atan(i / 512) in degrees for i < 512, then the word 0x103729c0. Float bit patterns. */\n");
    fprintf(out, "static const uint32_t kTrigSine[0x200] = {\n");
    for (i = 0; i < 0x200; i++)
        fprintf(out, "%s0x%08lx,%s", i % 8 == 0 ? "    " : " ", (unsigned long)sine[i], i % 8 == 7 ? "\n" : "");
    fprintf(out, "};\nstatic const uint32_t kTrigAtan[0x200] = {\n");
    for (i = 0; i < 0x200; i++)
        fprintf(out, "%s0x%08lx,%s", i % 8 == 0 ? "    " : " ", (unsigned long)atan[i], i % 8 == 7 ? "\n" : "");
    fprintf(out, "};\nstatic const uint32_t kTrigSineEnd = 0x%08lx, kTrigAtanEnd = 0x%08lx;\n",
            (unsigned long)sine[0x200], (unsigned long)atan[0x200]);
    fclose(out);
    printf("captured: sine[0]=%08lx sine[256]=%08lx atan[511]=%08lx ends %08lx %08lx\n", (unsigned long)sine[0],
           (unsigned long)sine[256], (unsigned long)atan[511], (unsigned long)sine[0x200],
           (unsigned long)atan[0x200]);
    return 0;
}
